import type { ExtractionOutcome } from '../../packages/core/src';
import { type CuadContract, LABELS, type Label, type SampleOptions } from './cuad';
import { type Metrics, type PairScore, aggregate, rate, scoreContract } from './score';

/** Everything one eval run produced. Saved under eval/data/runs (git-ignored: it holds CUAD quotes). */
export interface EvalRun {
  startedAt: string;
  finishedAt: string;
  split: 'eval' | 'dev';
  sample: SampleOptions;
  /** The model id requested: core's PRODUCTION_MODEL. */
  model: string;
  /** What the API said answered. */
  reportedModels: string[];
  sdkVersion: string;
  apiVersion: string;
  temperature: number;
  extractorVersion: number;
  schemaVersion: number;
  criticEnabled: boolean;
  contracts: Array<{ id: string; chars: number; ms: number; outcome: ExtractionOutcome }>;
}

/** Haiku 4.5 list prices, dollars per million tokens. */
const PRICE = { input: 1, output: 5 };

const pct = (num: number, den: number): string => {
  const r = rate(num, den);
  return r === null ? 'n/a' : `${(r * 100).toFixed(1)}% (${num}/${den})`;
};

const short = (id: string): string => (id.length > 60 ? `${id.slice(0, 57)}...` : id);

function cell(score: PairScore | undefined): string {
  if (!score) return '';
  const answer = { value: 'value', abstained: 'held', none: 'none' }[score.answer];
  if (score.goldClass === 'scorable') return score.exact ? 'exact' : `${answer === 'value' ? 'wrong' : answer}`;
  if (score.goldClass === 'blank') return score.answer === 'value' ? 'blank: gave value' : 'blank: withheld';
  if (score.goldClass === 'none') return score.answer === 'value' ? 'no CUAD value: gave one' : '';
  return `unscored (${answer})`;
}

function row(name: string, m: Metrics): string {
  return `| ${name} | ${m.scorable} | ${pct(m.exact, m.scorable)} | ${pct(m.exact, m.answered)} | ${pct(m.abstained, m.scorable)} | ${pct(m.noAnswer, m.scorable)} | ${pct(m.clauseHits, m.clauseGold)} |`;
}

export function scoreRun(run: EvalRun, cuad: ReadonlyMap<string, CuadContract>): PairScore[] {
  return run.contracts.flatMap((c) => {
    const contract = cuad.get(c.id);
    return contract ? scoreContract(contract, c.outcome) : [];
  });
}

export function renderReport(run: EvalRun, cuad: ReadonlyMap<string, CuadContract>): string {
  const scores = scoreRun(run, cuad);
  const byLabel = (label: Label) => aggregate(scores.filter((s) => s.label === label));
  const all = aggregate(scores);
  const notice = byLabel('Notice Period To Terminate Renewal');

  const ok = run.contracts.flatMap((c) => (c.outcome.status === 'ok' ? [c.outcome] : []));
  const failed = run.contracts.filter((c) => c.outcome.status === 'failed');
  const tokensIn = run.contracts.reduce((n, c) => n + c.outcome.usage.inputTokens, 0);
  const tokensOut = run.contracts.reduce((n, c) => n + c.outcome.usage.outputTokens, 0);
  const cost = (tokensIn * PRICE.input + tokensOut * PRICE.output) / 1_000_000;
  const calls = run.contracts.reduce((n, c) => n + c.outcome.calls, 0);
  const returned = ok.reduce((n, o) => n + o.grounding.quotesReturned, 0);
  const verified = ok.reduce((n, o) => n + o.grounding.quotesVerified, 0);
  const secondPasses = ok.reduce((n, o) => n + o.secondPasses, 0);
  const repaired = ok.filter((o) => o.repaired).length;
  const times = run.contracts.map((c) => c.ms).sort((a, b) => a - b);
  const median = times[Math.floor(times.length / 2)] ?? 0;
  const withNotice = run.contracts.filter((c) => /\d/.test(cuad.get(c.id)?.answers['Notice Period To Terminate Renewal'] ?? '')).length;

  const whys = new Map<string, number>();
  for (const s of scores) if (s.answer === 'abstained' && s.why !== undefined) whys.set(`${s.label}: ${s.why || 'unspecified'}`, (whys.get(`${s.label}: ${s.why || 'unspecified'}`) ?? 0) + 1);
  const anniversary = scores.filter((s) => s.matchedConvention === 'anniversary').length;
  const dayBefore = scores.filter((s) => s.matchedConvention === 'day_before_anniversary').length;

  const lines = [
    '# Covenant extraction eval',
    '',
    `Real numbers from running \`packages/core\` (extractor version ${run.extractorVersion}, schema version ${run.schemaVersion}) on ${run.contracts.length} CUAD contracts, ${run.finishedAt.slice(0, 10)}. Generated by \`npm run eval\`; do not edit by hand.`,
    '',
    '| | |',
    '| --- | --- |',
    `| Model | \`${run.model}\`, the production model id. The API reported: ${run.reportedModels.map((m) => `\`${m}\``).join(', ') || 'none'}. |`,
    `| Calls | Anthropic Messages API ${run.apiVersion} through \`@anthropic-ai/sdk\` ${run.sdkVersion}, temperature ${run.temperature}, one tool forced with \`tool_choice\`, critic ${run.criticEnabled ? 'on' : 'off'}. Production makes the same calls through Forge LLMs. |`,
    `| Sample | ${run.split === 'eval' ? 'Scored split' : 'Dev split (not the scored sample)'}: ${run.contracts.length} CUAD v1 contracts of at most ${run.sample.maxChars.toLocaleString('en-US')} characters, seed ${run.sample.seed}; ${withNotice} have a CUAD notice-period answer. |`,
    `| Cost | ${tokensIn.toLocaleString('en-US')} input and ${tokensOut.toLocaleString('en-US')} output tokens over ${calls} calls, about $${cost.toFixed(2)} at $${PRICE.input}/$${PRICE.output} per million. |`,
    `| Time | median ${(median / 1000).toFixed(1)} s per contract, ${secondPasses} second passes, ${repaired} answers repaired once. |`,
    '',
    '## Results',
    '',
    '| Label | Pairs with a CUAD value | Exact match | Exact when answered | Abstained | No answer | Clause recall |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...LABELS.map((label) => row(label, byLabel(label))),
    row('**All four**', all),
    '',
    `**Notice periods: ${pct(notice.exact, notice.scorable)} exact match** against the 85% target, which is a target and not a promise.`,
    '',
    `**Grounding: ${pct(verified, returned)}** of the quotes the model returned were found verbatim in the contract. The rest were dropped before scoring, as they are in production.`,
    '',
    'Exact match counts an abstention or a missing answer as a miss. "Exact when answered" is the share of values Covenant did give that were right: the number a reviewer feels.',
    '',
    `Expiration dates: ${dayBefore} matched with the term ending the day before the anniversary (Covenant's default), ${anniversary} only with the term ending on the anniversary. CUAD does not say which convention its annotators used.`,
    '',
    '## Why values were withheld',
    '',
    ...(whys.size === 0
      ? ['No abstentions.']
      : ['| Label: reason | Count |', '| --- | --- |', ...[...whys.entries()].sort((a, b) => b[1] - a[1]).map(([why, n]) => `| ${why} | ${n} |`)]),
    '',
    '## Other checks',
    '',
    `- Dates the contract left blank (CUAD writes \`[]\`): ${pct(all.blankWithheld, all.blankGold)} withheld. Giving a value there would be a guess.`,
    `- Values where CUAD has no answer at all: ${all.valueWithoutGold}. Not all are wrong, since CUAD can miss a clause; they are listed per contract below.`,
    `- Failed extractions: ${failed.length === 0 ? 'none' : failed.map((c) => `${short(c.id)} (${c.outcome.status === 'failed' ? c.outcome.reason : ''})`).join('; ')}.`,
    '',
    '## Per contract',
    '',
    'exact: matches CUAD. wrong: a different value. held: found but withheld for review. none: nothing found. Blank cells: CUAD has no answer and neither do we.',
    '',
    '| Contract | Chars | Effective | Expiration | Renewal | Notice | Calls |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...run.contracts.map((c) => {
      const s = scores.filter((p) => p.contract === c.id);
      const get = (label: Label) => cell(s.find((p) => p.label === label));
      return `| ${short(c.id)} | ${c.chars.toLocaleString('en-US')} | ${get('Effective Date')} | ${get('Expiration Date')} | ${get('Renewal Term')} | ${get('Notice Period To Terminate Renewal')} | ${c.outcome.calls} |`;
    }),
    '',
    '## Method',
    '',
    '- Each contract\'s CUAD text goes to `extractContract` as one unpaginated page, with production defaults. Nothing is tuned on these 30: prompt work uses the separate dev split (`npm run eval -- --dev`).',
    '- Pairs are (contract, label). A pair is scored for exact match when CUAD\'s answer column holds a usable value: a full date, a period such as "90 days", or "perpetual" for expiration.',
    '- Effective date: Covenant\'s date must equal CUAD\'s m/d/yy answer (two-digit year compared). Expiration: the date engine\'s end of the initial term from the verified effective date and term; "perpetual" matches a term that runs until terminated. Renewal term and notice period: equal length as stated, where 12 months equals 1 year but 90 days does not equal 3 months.',
    '- Notice period is the offset of Covenant\'s ready `renewal_notice` rules anchored at `term_end` with direction `before`. Two different ready offsets count as an abstention.',
    '- Clause recall: one of Covenant\'s verified quotes for that label shares at least half of the shorter span with a CUAD-highlighted span.',
    '- CUAD text has no page breaks, so page derivation is not measured here; it is covered by unit tests and spike S1.',
    '',
    'Reproduce: put `CUAD_v1.json` and `master_clauses.csv` in `eval/data/cuad/` (see `eval/README.md`), set `ANTHROPIC_API_KEY`, run `npm run eval`.',
    '',
    '## Credit',
    '',
    'CUAD v1, the Contract Understanding Atticus Dataset, by The Atticus Project, licensed CC BY 4.0: https://doi.org/10.5281/zenodo.4595826. Hendrycks, Burns, Chen and Ball, "CUAD: An Expert-Annotated NLP Dataset for Legal Contract Review", NeurIPS 2021.',
    '',
  ];
  return lines.join('\n');
}
